from __future__ import annotations

import json
import logging
import os
import shutil
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Any

import pandas as pd

from config import settings

log = logging.getLogger(__name__)

BRONZE_EXTENSIONS = (".jsonl", ".json", ".parquet", ".csv")


def partition_dir(bronze_dir: Path, dt: str, source_tag: str) -> Path:
    folder = bronze_dir / f"dt={dt}" / f"source={source_tag}"
    folder.mkdir(parents=True, exist_ok=True)
    return folder


def land_records(
    records: list[dict[str, Any]],
    bronze_dir: Path,
    event_date: str | None = None,
    fmt: str = "jsonl",
    source_tag: str = "batch",
) -> Path:
    settings.ensure_dirs()
    dt = event_date or date.today().isoformat()
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    path = partition_dir(bronze_dir, dt, source_tag) / f"part-{stamp}.{fmt}"
    if fmt == "jsonl":
        with open(path, "w", encoding="utf-8") as fh:
            for record in records:
                fh.write(json.dumps(record, default=str) + "\n")
    elif fmt == "parquet":
        pd.DataFrame(records).to_parquet(path, index=False)
    else:
        raise ValueError(f"Unsupported format: {fmt}")
    _upload_to_azure(path)
    return path


def write_partition(data: pd.DataFrame | list[str], bronze_dir: Path, dt: str, source_tag: str, name: str) -> Path | None:
    """Write one deterministic bronze file (re-runs overwrite instead of piling up copies)."""
    if (isinstance(data, pd.DataFrame) and data.empty) or (isinstance(data, list) and not data):
        return None
    path = partition_dir(bronze_dir, dt, source_tag) / name
    if isinstance(data, list):
        path.write_text("\n".join(data) + "\n", encoding="utf-8")
    elif name.endswith(".parquet"):
        data.to_parquet(path, index=False)
    else:
        data.to_csv(path, index=False)
    _upload_to_azure(path)
    return path


def land_raw_file(src: Path, bronze_dir: Path, dt: str, source_tag: str) -> Path:
    """Copy a dropped file into bronze byte-for-byte; bronze keeps the original format."""
    path = partition_dir(bronze_dir, dt, source_tag) / src.name
    shutil.copyfile(src, path)
    _upload_to_azure(path)
    return path


def reset_lake() -> None:
    """Remove all bronze data and the local stream outbox (everything is regenerated by ingestion)."""
    for target in (settings.LAKE_DIR / "bronze", settings.OUTBOX_DIR):
        if target.exists():
            shutil.rmtree(target)
    for pattern in ("budget_*.csv", "pos_legacy_*.csv", "manual_adjustments_*.csv"):
        for generated in settings.FILES_DIR.glob(pattern):
            generated.unlink()
    for generated in settings.SHAREPOINT_EXPORT_DIR.glob("*.csv"):
        generated.unlink()
    settings.ensure_dirs()


def _upload_to_azure(local_path: Path) -> str | None:
    if not settings.AZURE_STORAGE_CONNECTION_STRING:
        return None
    try:
        from azure.storage.blob import BlobServiceClient
    except ImportError:
        log.warning("AZURE_STORAGE_CONNECTION_STRING set but azure-storage-blob not installed; skipping upload")
        return None
    container = settings.AZURE_CONTAINER
    rel = local_path.relative_to(settings.LAKE_DIR).as_posix()
    service = BlobServiceClient.from_connection_string(settings.AZURE_STORAGE_CONNECTION_STRING)
    try:
        container_client = service.get_container_client(container)
        if not container_client.exists():
            container_client.create_container()
        with open(local_path, "rb") as data:
            container_client.upload_blob(name=rel, data=data, overwrite=True)
    finally:
        service.close()
    log.info("Uploaded bronze file to Azure: %s/%s", container, rel)
    return f"azure://{container}/{rel}"


def iter_bronze_files(bronze_dir: Path) -> list[Path]:
    if not bronze_dir.exists():
        return []
    files: list[Path] = []
    for root, _dirs, names in os.walk(bronze_dir):
        for name in sorted(names):
            if name.endswith(BRONZE_EXTENSIONS):
                files.append(Path(root) / name)
    return sorted(files)


def count_file_rows(path: Path) -> int:
    """Row count without loading the file: parquet footer metadata, line counts for text formats."""
    if path.suffix == ".parquet":
        import pyarrow.parquet as pq

        return pq.ParquetFile(path).metadata.num_rows
    with open(path, "rb") as fh:
        lines = sum(1 for line in fh if line.strip())
    return max(lines - 1, 0) if path.suffix == ".csv" else lines


def bronze_stats() -> dict[str, int]:
    def total(d: Path) -> int:
        return sum(count_file_rows(f) for f in iter_bronze_files(d))

    return {
        "transactions": total(settings.BRONZE_TXN_DIR),
        "invoices": total(settings.BRONZE_INVOICE_DIR),
        "budgets": total(settings.BRONZE_BUDGET_DIR),
        "masters": total(settings.BRONZE_MASTER_DIR),
        "ap_invoices": total(settings.BRONZE_AP_DIR),
        "fx_rates": total(settings.BRONZE_FX_DIR),
    }
